/**
 * Database Seed: Populates official verified foods catalog from USDA FoodData Central (FDC).
 * Enforces zero-fabrication: only independently verified food records with authentic FDC IDs.
 *
 * Serving Calculation Contract:
 * - Reference nutrient values (calories, protein, carbs, fat, fiber) are stored strictly per 100g (servingBasis = '100g').
 * - Each food defines a standard serving: servingSize (number), servingUnit (string), and exact servingWeightG (grams).
 * - For liquids/volumetric items, servingVolumeMl and densityGPerMl are explicitly provided (1ml != 1g).
 * - Effective portion nutrients for multiplier m = m * (servingWeightG / 100) * referenceValue.
 */
