def test_performance_evaluator_cost_parity_ttft_and_cancellation() -> None:
    ev = PerformanceEvaluator()
    in_tok, out_tok, cached_tok = 2000, 400, 500
    expected_cost = estimate_cost_usd("gemini-2.5-flash", in_tok, out_tok, cached_tok)

    ok_res = ev.evaluate(
        candidate={
            "model": "gemini-2.5-flash",
            "duration_ms": 950.0,
            "ttft_ms": 310.0,
            "input_tokens": in_tok,
            "output_tokens": out_tok,
            "cached_tokens": cached_tok,
            "total_tokens": in_tok + out_tok,
            "estimated_cost_usd": expected_cost,
            "chunks_emitted": 12,
            "outcome": "cancelled",
            "post_cancel_chunks": 0,
            "cancellation_latency_ms": 60.0,
        },
        input_payload={
            "max_latency_ms": 1500.0,
            "max_ttft_ms": 500.0,
            "max_total_tokens": 3000,
            "max_cost_usd": 0.01,
            "min_chunks": 5,
            "max_cancellation_latency_ms": 200.0,
        },
        expected_outcome="cancelled",
    )
    assert ok_res.passed is True

    bad_res = ev.evaluate(
        candidate={
            "model": "gemini-2.5-flash",
            "duration_ms": 6000.0,
            "ttft_ms": 2100.0,
            "input_tokens": 1000,
            "output_tokens": 500,
            "total_tokens": 1500,
            "estimated_cost_usd": 99.99,
            "chunks_emitted": 1,
            "outcome": "ok",
            "post_cancel_chunks": 4,
            "cancellation_latency_ms": 900.0,
        },
        input_payload={
            "max_latency_ms": 2000.0,
            "max_ttft_ms": 800.0,
            "min_chunks": 3,
        },
        expected_outcome="cancelled",
    )
    assert bad_res.passed is False
    assert bad_res.failure_classification == "performance_failure"
    assert len(bad_res.failure_reasons) >= 4

    assert compute_percentile([10.0, 20.0, 30.0, 40.0], 50.0) == 25.0
    summary = summarize_performance_results(
        [
            {
                "duration_ms": 50.0,
                "expected_outcome": "cancelled",
                "performance": ok_res.details["performance"],
            }
        ]
    )
    assert summary["clean_cancellation_rate"] == 1.0


@pytest.mark.asyncio
async def test_llm_judge_disabled_by_default_and_mocked_debiasing() -> None:
    # Default config is disabled and never invokes any callable
    called = False

    def _never_call(_prompt: str) -> str:
        nonlocal called
        called = True
        return "{}"

    default_judge = StructuredLlmJudge(judge_fn=_never_call)
    res_disabled = await default_judge.evaluate_pointwise(
        question="Safe progression?", candidate_text="Consult a doctor if sharp pain arises."
    )
    assert res_disabled.executed is False
    assert res_disabled.status == "DISABLED"
    assert called is False

    # Identity hint stripping
    assert "[model]" in sanitize_candidate_for_judge("Generated by gemini-2.5-flash model")

    # Enabled mocked pointwise judge + verbosity check + fail-closed malformed JSON
    async def _mock_judge(prompt: str) -> str:
        assert "[model]" in prompt
        return json.dumps(
            {
                "scores": {
                    "clinical_safety": 5,
                    "grounding": 3,
                    "cultural_clarity": 4,
                    "actionability": 4,
                },
                "rationale": "Grounded with room for tighter conciseness.",
            }
        )

    long_text = ("word " * 230) + "by gemini-2.5-pro"
    enabled_judge = StructuredLlmJudge(
        config=JudgeConfig(enabled=True, judge_model="mock-judge-v1"),
        judge_fn=_mock_judge,
    )
    res_point = await enabled_judge.evaluate_pointwise(
        question="Macros?",
        candidate_text=long_text,
        reference_facts=["58 kcal per idli"],
    )
    assert res_point.executed is True
    assert res_point.verbosity_bias_flagged is True
    assert "verbosity_penalty_applied" in res_point.bias_controls_applied

    malformed_judge = StructuredLlmJudge(
        config=JudgeConfig(enabled=True),
        judge_fn=lambda _p: "not valid json",
    )
    res_err = await malformed_judge.evaluate_pointwise(question="Q", candidate_text="A")
    assert res_err.status == "PARSE_ERROR"
    assert res_err.passed is False


@pytest.mark.asyncio
async def test_llm_judge_pairwise_position_swap_resolves_bias_to_tie() -> None:
    # Judge always picks Option 1 regardless of content -> position bias
    first_slot_biased = StructuredLlmJudge(
        config=JudgeConfig(enabled=True, enforce_position_swap=True),
        judge_fn=lambda _p: json.dumps({"winner": "1", "rationale": "First option bias"}),
    )
    res_bias = await first_slot_biased.pairwise_compare(
        question="Workout plan?", candidate_a="Option A", candidate_b="Option B"
    )
    assert res_bias.order_consistent is False
    assert res_bias.winner == "tie"
    assert "position_swap_debiasing" in res_bias.bias_controls_applied

    # Judge consistently prefers whichever slot holds "Safe concise plan"
    consistent = StructuredLlmJudge(
        config=JudgeConfig(enabled=True, enforce_position_swap=True),
        judge_fn=lambda prompt: json.dumps(
            {
                "winner": "1"
                if prompt.split("[Option 1]:")[1].split("[Option 2]:")[0].strip().startswith("Safe")
                else "2",
                "rationale": "Clinically grounded",
            }
        ),
    )
    res_ok = await consistent.pairwise_compare(
        question="Plan?", candidate_a="Safe concise plan", candidate_b="Unsafe fluff"
    )
    assert res_ok.order_consistent is True
    assert res_ok.winner == "candidate_a"


def test_regression_gate_enforces_safety_baseline_and_slos() -> None:
    baseline = {
        "summary": {"total_cases": 2, "average_score": 1.0},
        "category_breakdown": {
            "security_adversarial": {"pass_rate": 1.0},
            "rag_evaluation": {"pass_rate": 1.0},
        },
        "passed_case_ids": ["CASE_SEC_1", "CASE_RAG_1"],
    }
    failing_report = {
        "summary": {"total_cases": 2, "average_score": 0.5},
        "performance_summary": {
            "p95_latency_ms": 9500.0,
            "avg_tokens_per_case": 5000.0,
            "total_estimated_cost_usd": 2.5,
        },
        "results": [
            {
                "case_id": "CASE_SEC_1",
                "category": "security_adversarial",
                "passed": False,
                "score": 0.0,
                "failure_classification": "security_failure",
            },
            {
                "case_id": "CASE_RAG_1",
                "category": "rag_evaluation",
                "passed": True,
                "score": 1.0,
                "failure_classification": "none",
            },
        ],
    }

    gate = evaluate_regression_gate(
        failing_report, baseline=baseline, thresholds=RegressionGateThresholds()
    )
    assert gate.passed is False
    assert gate.critical_safety_failed is True
    assert any("Critical safety/security gate failed" in r for r in gate.regressions)
    assert any("p95 latency" in r for r in gate.regressions)
    assert any("Previously passing cases regressed" in r for r in gate.regressions)
