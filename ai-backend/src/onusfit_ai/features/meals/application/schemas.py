"""Pydantic schemas for Gemini Native Structured Outputs in Meals (Voice & Photo)."""

import os
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field
from pydantic.alias_generators import to_camel


def is_voice_meal_structured_output_enabled() -> bool:
    """Feature toggle for Gemini Native Structured Outputs in Voice Meal."""
    flag = os.getenv("AI_VOICE_MEAL_STRUCTURED_OUTPUTS", "true").strip().lower()
    return flag not in ("0", "false", "no", "off")


def is_meal_photo_structured_output_enabled() -> bool:
    """Feature toggle for Gemini Native Structured Outputs in Meal Photo."""
    flag = os.getenv("AI_PHOTO_MEAL_STRUCTURED_OUTPUTS", "true").strip().lower()
    return flag not in ("0", "false", "no", "off")


class GeminiDetectedFoodItemOutput(BaseModel):
    """Single food item generated by Gemini."""

    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
    )

    name: str = Field(description="Standard Food Name")
    portion_description: str | None = Field(
        default=None, description="e.g. 2 pieces · 160 g or 1 bowl · 200 g"
    )
    serving_weight_g: float | None = Field(default=None, description="Serving weight in grams")
    serving_unit: str | None = Field(
        default=None, description="Serving unit e.g. piece, cup, bowl, slice"
    )
    serving_size: float | None = Field(default=None, description="Portion count e.g. 1, 2, 0.5")
    calories: float = Field(default=0.0, ge=0, description="Estimated energy in kcal")
    protein_g: float = Field(default=0.0, description="Protein in grams")
    carbs_g: float = Field(default=0.0, description="Carbohydrates in grams")
    fat_g: float = Field(default=0.0, description="Fat in grams")
    fiber_g: float | None = Field(default=None, description="Dietary fiber in grams")
    confidence: Literal["high", "medium", "low"] = "medium"


class GeminiVoiceMealOutput(BaseModel):
    """Root generation schema for Gemini Native Structured Outputs in Voice Meal."""

    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
    )

    transcript: str = Field(default="", description="Transcribed or confirmed speech text")
    detected_language: Literal["en", "ta", "tanglish"] = "en"
    confidence: Literal["high", "medium", "low"] = "medium"
    unclear_reason: str | None = None
    items: list[GeminiDetectedFoodItemOutput] = Field(default_factory=list)


class GeminiPhotoMealOutput(BaseModel):
    """Root generation schema for Gemini Native Structured Outputs in Meal Photo."""

    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
    )

    is_food: bool = Field(
        default=True, description="Whether the image contains recognizable food or beverage"
    )
    summary: str = Field(default="", description="Short 1-sentence summary of the meal")
    confidence: Literal["high", "medium", "low"] = "medium"
    unclear_reason: str | None = None
    items: list[GeminiDetectedFoodItemOutput] = Field(default_factory=list)
